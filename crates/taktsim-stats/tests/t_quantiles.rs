#[test]
fn quantiles_match_mpmath() {
    let mut worst = (0.0_f64, 0, 0.0);
    for (df, p, expected) in REFERENCE {
        let found = StudentT::new(df)
            .unwrap()
            .quantile(Probability::new(p).unwrap());
        let error = ((found - expected) / expected).abs();
        assert!(
            error <= TOLERANCE,
            "df {df}, p {p}: found {found}, expected {expected}, relative error {error:e}"
        );
        if error > worst.0 {
            worst = (error, df, p);
        }
    }
    // Shown with `cargo test -- --nocapture`.
    println!(
        "largest relative error {:e} at df {}, p {}",
        worst.0, worst.1, worst.2
    );
}

#[test]
fn critical_values_are_the_upper_quantiles() {
    // α/2 = (1 − level)/2 equals 1 − p for these levels up to rounding of
    // the literal, so the two agree to the tolerance.
    for (df, p, expected) in REFERENCE {
        if p <= 0.75 || p >= 0.999_999 {
            continue;
        }
        let level = ConfidenceLevel::from_alpha(2.0 * (1.0 - p)).unwrap();
        let found = StudentT::new(df).unwrap().critical_value(level);
        let error = ((found - expected) / expected).abs();
        assert!(
            error <= TOLERANCE,
            "df {df}, level {level}: {found} vs {expected}"
        );
    }
}

#[test]
fn quantiles_are_odd_and_increasing() {
    for df in [1, 2, 3, 7, 30, 2999, 3000, 1_000_000] {
        let t = StudentT::new(df).unwrap();
        let mut previous = f64::NEG_INFINITY;
        for i in 1..1000 {
            let p = f64::from(i) / 1000.0;
            let q = t.quantile(Probability::new(p).unwrap());
            assert!(q > previous, "df {df}: not increasing at p = {p}");
            previous = q;
            // 1 − p is exact for p ≥ 1/2; check symmetry on those.
            if p >= 0.5 {
                let mirrored = t.quantile(Probability::new(1.0 - p).unwrap());
                assert_eq!(mirrored, -q, "df {df}, p {p}");
            }
        }
    }
}

#[test]
fn extreme_tails_stay_finite_and_ordered() {
    // Far beyond any confidence level: no NaN, no infinity, still monotone
    // in p and decreasing in the degrees of freedom.
    for df in [1, 2, 3, 10, 2999, 100_000] {
        let t = StudentT::new(df).unwrap();
        let mut previous = 0.0;
        for exponent in [10, 50, 100, 200, 300] {
            let q = t.quantile(Probability::new(libm::pow(10.0, -f64::from(exponent))).unwrap());
            assert!(q.is_finite() && q < previous, "df {df}, 1e-{exponent}: {q}");
            previous = q;
        }
    }
    let p = Probability::new(1e-12).unwrap();
    let mut previous = f64::NEG_INFINITY;
    for df in [1, 2, 3, 5, 10, 100, 1000, 10_000] {
        let q = StudentT::new(df).unwrap().quantile(p);
        assert!(q > previous, "df {df}: {q}");
        previous = q;
    }
}

/// The smallest supported tail probability, the smallest normal f64, still
/// gives a finite quantile for every degree of freedom, and so does the
/// smallest supported α. Below it the constructors refuse (a subnormal α
/// once halved to 0 and gave NaN after a long Newton loop).
#[test]
fn the_smallest_supported_tails_give_finite_quantiles() {
    let p = Probability::new(f64::MIN_POSITIVE).unwrap();
    let level = ConfidenceLevel::from_alpha(2.0 * f64::MIN_POSITIVE).unwrap();
    for df in [1, 2, 3, 10, 2999, 3000, 1_000_000, u32::MAX] {
        let t = StudentT::new(df).unwrap();
        let q = t.quantile(p);
        assert!(q.is_finite() && q < 0.0, "df {df}: {q}");
        let c = t.critical_value(level);
        assert!(c.is_finite() && c > 0.0, "df {df}: {c}");
        assert_eq!(c, -q, "df {df}");
    }
    assert!(Probability::new(f64::MIN_POSITIVE / 2.0).is_err());
    assert!(ConfidenceLevel::from_alpha(f64::MIN_POSITIVE).is_err());
}
